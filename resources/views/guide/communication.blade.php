{{-- User guide: communication. --}}
<p>Announcements, message templates and staff chat.</p>
<details>
    <summary>Send an announcement</summary>
    <p class="dash-guide-where">Where: Announcements</p>
    <ol>
        <li>Write the title and message, choose who gets it (students, parents, staff, classes…).</li>
        <li>It always appears in everyone's bell; tick mobile push, SMS or email for extra copies.</li>
        <li>Schedule it for later or publish now.</li>
    </ol>
    
</details>
<details>
    <summary>Message templates</summary>
    <p class="dash-guide-where">Where: Announcements → Templates</p>
    <ol>
        <li>Edit the wording of automatic messages (absent, challan, payment, results…).</li>
        <li>Bell messages always go out; SMS / WhatsApp / email copies go when their template is active and the provider is set up.</li>
    </ol>
    
</details>
<details>
    <summary>Staff chat</summary>
    <p class="dash-guide-where">Where: Menu → Chat</p>
    <ol>
        <li>One-to-one and group chats with colleagues.</li>
    </ol>
    
</details>
