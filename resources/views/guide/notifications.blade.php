{{-- User guide: notifications. --}}
<p>Every notification always appears in the <strong>bell</strong> at the top of the portal (and on the mobile app). SMS, WhatsApp and email are extra copies only when the school has switched them on.</p>
<details>
    <summary>Read your notifications</summary>
    <p class="dash-guide-where">Where: Bell icon, top right</p>
    <ol>
        <li>A red number shows unread notifications.</li>
        <li>Click the bell to see the latest; click one to open the related page.</li>
        <li>Use <strong>Mark all read</strong> to clear the count.</li>
    </ol>
    <p class="dash-guide-tip">Urgent notices are shown in red.</p>
</details>
<details>
    <summary>What you are told about</summary>
    
    <ol>
        <li>Parents and students: absence, arrival at the gate, challans, payments received, fee reminders, results, diary, leave decisions, online tests, library books.</li>
        <li>Staff: approvals waiting, follow-ups due, substitutions, fees overdue, daily summary (principal).</li>
        <li>Everyone: school announcements.</li>
    </ol>
    
</details>
