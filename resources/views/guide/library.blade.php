{{-- User guide: library. --}}
<p>Books, copies, lending and fines.</p>
<details>
    <summary>Add books</summary>
    <p class="dash-guide-where">Where: Library → Books</p>
    <ol>
        <li>Press <strong>Add Book</strong>, fill the title and author and how many copies.</li>
        <li>Each copy gets an accession number (ACC-000001…). Write it on the book's label.</li>
        <li>Open a book to see its copies and mark one damaged, lost or withdrawn.</li>
    </ol>
    
</details>
<details>
    <summary>Set the rules</summary>
    <p class="dash-guide-where">Where: Library → Books (top)</p>
    <ol>
        <li>Loan period in days, books at a time, and late fine per day.</li>
    </ol>
    
</details>
<details>
    <summary>Issue and return</summary>
    <p class="dash-guide-where">Where: Library → Issue &amp; Return</p>
    <ol>
        <li>Type or scan the accession number, choose Student or Staff and pick the person, then <strong>Issue book</strong>.</li>
        <li>When it comes back press <strong>Return</strong> (or <strong>Lost</strong>).</li>
        <li>A late return adds a Library Fine challan for students.</li>
    </ol>
    <p class="dash-guide-tip">Families are reminded the day after a book is due and weekly after that.</p>
</details>
