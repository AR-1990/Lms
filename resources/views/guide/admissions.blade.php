{{-- User guide: admissions. --}}
<p>From the first enquiry to an enrolled student.</p>
<details>
    <summary>Record an enquiry and follow up</summary>
    <p class="dash-guide-where">Where: Admissions → Inquiries</p>
    <ol>
        <li>Press <strong>New Inquiry</strong>; only the parent's name and phone are needed.</li>
        <li>Set the source and the follow-up date.</li>
        <li>Open <strong>Follow-ups</strong> on a row to log each call or visit and set the next date.</li>
        <li>You get a reminder every morning for enquiries due.</li>
    </ol>
    <p class="dash-guide-tip">The report "Enquiries by Source" shows which sources bring admissions.</p>
</details>
<details>
    <summary>Applications to enrolment</summary>
    <p class="dash-guide-where">Where: Admissions → Applications</p>
    <ol>
        <li>Convert an enquiry or add an application with the student and guardians.</li>
        <li>Record the test and interview, then accept.</li>
        <li>Enrol: choose the class and section. The system can create the student login, this month's challan and the ID card.</li>
    </ol>
    
</details>
