{{-- User guide: parent. --}}
<p>Everything about your child is on one page. If you have more than one child, switch between them at the top.</p>
<details>
    <summary>Open your child's page</summary>
    <p class="dash-guide-where">Where: Menu → Child Overview</p>
    <ol>
        <li>The top shows the class, roll number, class teacher and bus.</li>
        <li>Tiles show this month's attendance, fees due, the next exam paper and the latest result.</li>
        <li>Use the tabs: Today, Attendance, Exams &amp; Results, Fees, Leave, Year by year.</li>
    </ol>
    
</details>
<details>
    <summary>Pay fees</summary>
    <p class="dash-guide-where">Where: Child Overview → Fees tab</p>
    <ol>
        <li>Download the challan and pay at the bank, <em>or</em> pay online by JazzCash, EasyPaisa or bank transfer to the account shown.</li>
        <li>After paying online, fill <strong>Paid online? Send the screenshot</strong>: choose the challan, amount, date and transaction ID, and attach the screenshot.</li>
        <li>The school checks it. You get the receipt in <strong>Payments</strong> and a notification, or the reason if it is not accepted.</li>
    </ol>
    <p class="dash-guide-tip">Each transaction ID can be sent only once.</p>
</details>
<details>
    <summary>Results and result cards</summary>
    <p class="dash-guide-where">Where: Child Overview → Exams &amp; Results</p>
    <ol>
        <li>See date sheets and download the admit card when it is ready.</li>
        <li>After results are published, see subject marks and download the result card.</li>
        <li>Online test scores are listed here too.</li>
    </ol>
    
</details>
<details>
    <summary>Ask for leave</summary>
    <p class="dash-guide-where">Where: Child Overview → Leave</p>
    <ol>
        <li>Choose the dates and write the reason, then <strong>Send request</strong>.</li>
        <li>The class teacher approves or rejects it and you are notified.</li>
    </ol>
    
</details>
<details>
    <summary>Diary and homework</summary>
    <p class="dash-guide-where">Where: Child Overview → Today</p>
    <ol>
        <li>Today's periods and the last two weeks of diary and homework are listed.</li>
        <li>Press <strong>Sign</strong> to show the teacher you have seen the diary.</li>
    </ol>
    
</details>
