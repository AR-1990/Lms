{{-- User guide: academics. --}}
<p>Session, classes, subjects, timetable and covers.</p>
<details>
    <summary>Set up the year</summary>
    <p class="dash-guide-where">Where: Academics</p>
    <ol>
        <li>Sessions → Classes → Sections → Subjects → Curriculum (subjects per class).</li>
        <li>Periods define the bell times; Calendar holds holidays and events.</li>
    </ol>
    
</details>
<details>
    <summary>Make the timetable</summary>
    <p class="dash-guide-where">Where: Academics → Timetable</p>
    <ol>
        <li>Pick a section and fill each day and period with a subject and teacher.</li>
        <li>A teacher cannot be in two places in the same period.</li>
    </ol>
    
</details>
<details>
    <summary>Cover absent teachers</summary>
    <p class="dash-guide-where">Where: Academics → Substitutions</p>
    <ol>
        <li>Pick the date. Teachers on leave or marked absent are listed with their periods.</li>
        <li>For each period choose a free teacher (fewest periods first) and press <strong>Assign</strong>.</li>
        <li>The cover teacher is told and sees it on their schedule.</li>
    </ol>
    
</details>
