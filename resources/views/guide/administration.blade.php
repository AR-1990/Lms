{{-- User guide: administration. --}}
<p>School-wide settings, users and data.</p>
<details>
    <summary>Users and roles</summary>
    <p class="dash-guide-where">Where: Users · Roles</p>
    <ol>
        <li>Add users and give them a role; roles are sets of permissions.</li>
        <li>Give a role an extra permission to open that module.</li>
    </ol>
    
</details>
<details>
    <summary>School settings and backups</summary>
    <p class="dash-guide-where">Where: Settings</p>
    <ol>
        <li>School name, logo, contact details and time zone.</li>
        <li>Backups run every night; you can make one now and download it.</li>
    </ol>
    
</details>
<details>
    <summary>Lists, numbering and campuses</summary>
    <p class="dash-guide-where">Where: Lookups · Numbering · Campuses</p>
    <ol>
        <li>Edit drop-down lists (relations, categories, reasons…).</li>
        <li>Set number formats for challans, receipts and certificates.</li>
        <li>With more than one campus, each campus sees its own records; head office picks a campus at the top.</li>
    </ol>
    
</details>
<details>
    <summary>Import data</summary>
    <p class="dash-guide-where">Where: Data Import</p>
    <ol>
        <li>Download the CSV template, fill it and upload.</li>
        <li>Press <strong>Check file</strong> first; rows with problems are listed. Nothing is saved until every row is right.</li>
    </ol>
    
</details>
