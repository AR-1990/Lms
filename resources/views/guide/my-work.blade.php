{{-- User guide: my-work. --}}
<p>Your own staff records: attendance, leave, payslips and loans.</p>
<details>
    <summary>Apply for leave</summary>
    <p class="dash-guide-where">Where: Menu → My HR</p>
    <ol>
        <li>Choose the leave type and dates, write the reason and send.</li>
        <li>You can see your balance for each leave type first.</li>
        <li>You are notified when it is approved or rejected.</li>
    </ol>
    
</details>
<details>
    <summary>Payslips and loans</summary>
    <p class="dash-guide-where">Where: Menu → My HR</p>
    <ol>
        <li>Download each month's payslip once payroll is posted.</li>
        <li>See loans or advances and what is left to repay.</li>
    </ol>
    
</details>
<details>
    <summary>Check in at the gate</summary>
    <p class="dash-guide-where">Where: Dashboard</p>
    <ol>
        <li>Show your attendance QR (or ID card) to the gate kiosk when you arrive and again when you leave.</li>
        <li>Arriving after your shift start and grace minutes is marked late.</li>
    </ol>
    
</details>
