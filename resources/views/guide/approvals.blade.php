{{-- User guide: approvals. --}}
<p>One page lists everything waiting for your decision.</p>
<details>
    <summary>Approve or reject</summary>
    <p class="dash-guide-where">Where: Menu → Approvals Inbox</p>
    <ol>
        <li>Requests are grouped: deletions, expenses, purchase orders, loans, concessions, online fee payments, staff leave and student leave.</li>
        <li>Press <strong>Approve</strong> or <strong>Reject</strong>; rejecting asks for a reason that the requester sees.</li>
    </ol>
    <p class="dash-guide-tip">Deleting records needs an administrator's approval; nothing is ever lost for good.</p>
</details>
