{{-- User guide: hr. --}}
<p>Staff from hiring to exit, and monthly payroll.</p>
<details>
    <summary>Staff records</summary>
    <p class="dash-guide-where">Where: HR → Employees</p>
    <ol>
        <li>Add staff with department, designation, shift and salary.</li>
        <li>Documents, qualifications and contracts are kept on the profile.</li>
    </ol>
    
</details>
<details>
    <summary>Leave and appraisals</summary>
    <p class="dash-guide-where">Where: HR → Leave · Appraisals</p>
    <ol>
        <li>Set leave types and approve requests; balances update by themselves.</li>
        <li>Run appraisal cycles with criteria and scores.</li>
    </ol>
    
</details>
<details>
    <summary>Payroll</summary>
    <p class="dash-guide-where">Where: HR → Payroll</p>
    <ol>
        <li>Run the month: attendance, leave, lates, loans and adjustments are worked out.</li>
        <li>Review, approve and post; payslips appear in each person's My HR.</li>
    </ol>
    
</details>
<details>
    <summary>Staff exit</summary>
    <p class="dash-guide-where">Where: HR → Staff Exits</p>
    <ol>
        <li>Start the exit; each area (accounts, library, IT, administration) clears it.</li>
        <li>The final settlement shows salary, leave encashment and loan recovery.</li>
        <li>Settle to post the payment, then print the experience letter.</li>
    </ol>
    <p class="dash-guide-tip">Assets and library books still held must be returned first.</p>
</details>
