{{-- User guide: teaching. --}}
<p>Daily classroom work: attendance, diary and homework, marks and online tests.</p>
<details>
    <summary>Mark attendance by hand</summary>
    <p class="dash-guide-where">Where: Attendance → Daily Register</p>
    <ol>
        <li>Choose your class and the date.</li>
        <li>Mark each student Present, Absent, Late, Leave or Half day (approved leave is filled in for you).</li>
        <li>Press <strong>Save</strong>. Parents of absent students are told.</li>
    </ol>
    <p class="dash-guide-tip">Students who scanned at the gate are already marked; you can still change them.</p>
</details>
<details>
    <summary>Diary and homework</summary>
    <p class="dash-guide-where">Where: Menu → Diary / Homework</p>
    <ol>
        <li>Choose the class and date, add entries (homework, classwork, tests, remarks) and publish.</li>
        <li>Parents get one notification and can sign the diary.</li>
    </ol>
    
</details>
<details>
    <summary>Enter exam marks</summary>
    <p class="dash-guide-where">Where: Exams → Marks Entry</p>
    <ol>
        <li>Choose the exam paper and your class.</li>
        <li>Type theory and practical marks, or tick Absent.</li>
        <li>Save as draft, then <strong>Submit</strong> when done. After submitting, changes need a reason; the exam cell approves the marks.</li>
    </ol>
    
</details>
<details>
    <summary>Make an online test</summary>
    <p class="dash-guide-where">Where: Exams → Online Tests</p>
    <ol>
        <li>Press <strong>New Test</strong>, pick the class and subject, and set the opening time, closing time and minutes allowed.</li>
        <li>Add questions with options and tick the right answer, or use <strong>Copy from a test</strong> or <strong>CSV</strong> (download the template first).</li>
        <li>Link it to an exam paper if the score should count as that paper's marks.</li>
        <li>Save, then <strong>Publish</strong>. Students are notified. Use <strong>Results</strong> to see scores.</li>
    </ol>
    <p class="dash-guide-tip">Questions lock once a student has started the test.</p>
</details>
<details>
    <summary>Periods you cover</summary>
    <p class="dash-guide-where">Where: Dashboard → Today's schedule</p>
    <ol>
        <li>Periods you cover for an absent teacher are marked <strong>Cover</strong> and you get a notification.</li>
    </ol>
    
</details>
