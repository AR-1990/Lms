{{-- User guide: fees. --}}
<p>Challans, receipts and every way families pay.</p>
<details>
    <summary>Challans</summary>
    <p class="dash-guide-where">Where: Fees → Challans</p>
    <ol>
        <li>Generate monthly challans for a class or all classes, or make one for a student.</li>
        <li>Print three-copy challans (bank, school, student) or a whole batch.</li>
        <li>Cancel or waive with a reason; paid challans are never edited.</li>
    </ol>
    
</details>
<details>
    <summary>Receive a payment</summary>
    <p class="dash-guide-where">Where: Fees → Receipts</p>
    <ol>
        <li>Find the student, choose the method and amount; it pays the oldest challans first.</li>
        <li>Extra money is kept as advance and used on the next challan.</li>
        <li>Print the receipt. A wrong receipt is reversed, not deleted.</li>
    </ol>
    
</details>
<details>
    <summary>Online payments by screenshot</summary>
    <p class="dash-guide-where">Where: Fees → Online Payments</p>
    <ol>
        <li>Families send the screenshot and transaction ID from their portal.</li>
        <li>Open one, compare it with your bank or wallet account, then <strong>Approve &amp; make receipt</strong> or <strong>Reject</strong> with the reason.</li>
    </ol>
    <p class="dash-guide-tip">Write the JazzCash / EasyPaisa / bank details families should pay to under Accounts → Payment Methods ("How families pay to this").</p>
</details>
<details>
    <summary>Automation: monthly challans, fines and reminders</summary>
    <p class="dash-guide-where">Where: Fees → Late Fees &amp; Automation</p>
    <ol>
        <li>Choose the day monthly challans are made by themselves.</li>
        <li>Set late fine rules (fixed, percent or per day).</li>
        <li>Choose how many days before the due date families are reminded.</li>
    </ol>
    
</details>
<details>
    <summary>Concessions and refunds</summary>
    <p class="dash-guide-where">Where: Fees → Concessions · Refunds</p>
    <ol>
        <li>Give a concession type to a student (some need approval).</li>
        <li>Refund deposits or unused advance from the student's profile.</li>
    </ol>
    
</details>
