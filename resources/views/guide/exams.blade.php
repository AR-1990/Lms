{{-- User guide: exams. --}}
<p>From the date sheet to printed result cards. Online tests can also fill exam marks.</p>
<details>
    <summary>Create an exam</summary>
    <p class="dash-guide-where">Where: Exams → Exams</p>
    <ol>
        <li>Press <strong>New Exam</strong>: term, class, exam type (monthly, mid term, semester, prelims…), grading scale and fee if any.</li>
        <li>Add the date sheet: subjects, dates, times, max and pass marks.</li>
        <li>Move it to <strong>Scheduled</strong>.</li>
    </ol>
    
</details>
<details>
    <summary>Admit cards and seating</summary>
    <p class="dash-guide-where">Where: Exams → open the exam</p>
    <ol>
        <li>Make exam fee challans if needed, then <strong>Issue admit cards</strong> (fee and attendance rules decide who is eligible; you can override).</li>
        <li>Print admit cards and make the seating plan per paper.</li>
    </ol>
    
</details>
<details>
    <summary>Marks, review and publishing</summary>
    <p class="dash-guide-where">Where: Exams → open the exam → Results</p>
    <ol>
        <li>Move to <strong>Marks entry</strong>; teachers enter marks.</li>
        <li>Approve each paper's marks, move to <strong>Review</strong>, check the tabulation.</li>
        <li>Press <strong>Publish results</strong>: grades, positions and result cards are made and families are told.</li>
    </ol>
    
</details>
<details>
    <summary>Remarks and result cards</summary>
    <p class="dash-guide-where">Where: Exams → open the exam → Results</p>
    <ol>
        <li>Pick the section and press <strong>Remarks</strong>. Write class teacher and principal remarks, or <strong>Fill empty from grade</strong>.</li>
        <li>Press <strong>Print result cards</strong> for the whole class or the chosen section: one professional A4 page per student.</li>
    </ol>
    <p class="dash-guide-tip">Parents and students download the same result card from their portal.</p>
</details>
<details>
    <summary>Online tests</summary>
    <p class="dash-guide-where">Where: Exams → Online Tests</p>
    <ol>
        <li>See "Make an online test" under Teaching. Tests linked to a paper write each score into marks for approval.</li>
    </ol>
    
</details>
