{{-- User guide: attendance. --}}
<p>Attendance can be taken at the gate (QR) and by teachers in the register; both work together.</p>
<details>
    <summary>Live Today board</summary>
    <p class="dash-guide-where">Where: Attendance → Live Today</p>
    <ol>
        <li>See students present, late, absent and not marked yet, class by class, and staff in and out.</li>
        <li>The latest arrivals show how each was recorded (gate, scanner, register). It refreshes every 15 seconds.</li>
        <li>Press <strong>Mark</strong> on a class to open its register.</li>
    </ol>
    
</details>
<details>
    <summary>Mark absent automatically</summary>
    <p class="dash-guide-where">Where: Attendance → Live Today → settings</p>
    <ol>
        <li>For schools that use gate scanning: set the time (e.g. 09:30) after which students with no mark are made absent.</li>
        <li>Parents get the absent alert. A student who scans later becomes late.</li>
        <li>Leave it empty if teachers mark the register.</li>
    </ol>
    
</details>
<details>
    <summary>Gate kiosk</summary>
    <p class="dash-guide-where">Where: Attendance → Gate Kiosks</p>
    <ol>
        <li>Press <strong>Add Kiosk</strong> and copy the link it shows (shown only once).</li>
        <li>Open the link on a tablet or phone at the gate and allow the camera.</li>
        <li>Students and staff show their ID card QR. Use <strong>New link</strong> if a device is lost.</li>
    </ol>
    <p class="dash-guide-tip">A USB barcode scanner also works: it types into the code box.</p>
</details>
<details>
    <summary>Staff attendance, shifts and biometric</summary>
    <p class="dash-guide-where">Where: Attendance → Staff Attendance · HR → Shifts · Data Import</p>
    <ol>
        <li>Mark staff in the staff register or by QR.</li>
        <li>Set shift times and grace minutes in HR → Shifts; lateness follows each person's shift.</li>
        <li>Import a biometric device CSV (employee code, date, time) under Data Import.</li>
    </ol>
    
</details>
<details>
    <summary>Student leave requests</summary>
    <p class="dash-guide-where">Where: Attendance → Leave Requests</p>
    <ol>
        <li>Approve or reject requests from parents; approved leave fills the register.</li>
    </ol>
    
</details>
