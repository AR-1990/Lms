{{-- User guide: students. --}}
<p>Each student has one profile with everything about them.</p>
<details>
    <summary>Find and open a student</summary>
    <p class="dash-guide-where">Where: Students</p>
    <ol>
        <li>Search by name or admission number and open the profile.</li>
        <li>Tabs show details, guardians, documents, fees, attendance, results and history.</li>
    </ol>
    
</details>
<details>
    <summary>Records and certificates</summary>
    <p class="dash-guide-where">Where: Student profile → Care &amp; records</p>
    <ol>
        <li>Add medical details, discipline notes (optionally tell the parents) and achievements.</li>
        <li>Issue a Bonafide or Character certificate; print it as a PDF.</li>
    </ol>
    
</details>
<details>
    <summary>Year-end promotion</summary>
    <p class="dash-guide-where">Where: Students → Year-end Promotion</p>
    <ol>
        <li>Choose the old and new session; copy sections and subjects.</li>
        <li>Each class lists students with the suggested move from results; change any row.</li>
        <li>Save, then make the new session current.</li>
    </ol>
    <p class="dash-guide-tip">A class can be undone until the new session has attendance, fees or results.</p>
</details>
<details>
    <summary>Student leaving</summary>
    <p class="dash-guide-where">Where: Student profile → Leaving &amp; clearance</p>
    <ol>
        <li>Check fee dues, school items and library books still held.</li>
        <li>Refund or adjust the deposit if needed.</li>
        <li>Issue the School Leaving Certificate.</li>
    </ol>
    
</details>
