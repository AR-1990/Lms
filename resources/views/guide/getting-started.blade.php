{{-- User guide: getting-started. --}}
<p>Pinnacle runs on the web and on the mobile app with the same account. Everything you see depends on your role.</p>
<details>
    <summary>Sign in and change your password</summary>
    <p class="dash-guide-where">Where: Sign-in page</p>
    <ol>
        <li>Open the school website and choose <strong>Sign in</strong>.</li>
        <li>Enter your email, user ID or admission number and your password.</li>
        <li>To change the password, open your name at the bottom of the menu.</li>
        <li>Forgot it? Use <strong>Forgot password</strong> on the sign-in page.</li>
    </ol>
    <p class="dash-guide-tip">Never share your password. Sign out on shared computers.</p>
</details>
<details>
    <summary>Find any page quickly (Jump to)</summary>
    <p class="dash-guide-where">Where: Search box in the top bar</p>
    <ol>
        <li>Click the <strong>Jump to…</strong> box or press <kbd>Ctrl</kbd> + <kbd>K</kbd> (or <kbd>/</kbd>).</li>
        <li>Type part of what you want, e.g. "challan", "marks" or "library".</li>
        <li>Use the arrow keys and press <kbd>Enter</kbd>, or click the page.</li>
    </ol>
    <p class="dash-guide-tip">Only pages you are allowed to open are listed.</p>
</details>
<details>
    <summary>Use the menu</summary>
    <p class="dash-guide-where">Where: Left sidebar</p>
    <ol>
        <li>Pick a module from the menu; its screens show as tabs at the top of the page.</li>
        <li>Use the arrow button at the top of the menu to make it narrow and get more space.</li>
        <li>On a phone, open the menu with the button at the top left.</li>
    </ol>
    
</details>
<details>
    <summary>Lists, search and export</summary>
    <p class="dash-guide-where">Where: Any list (grid)</p>
    <ol>
        <li>Type in the search box above a list to search everything in it.</li>
        <li>Use the boxes under the column titles to search one column.</li>
        <li>Use <strong>From / To</strong> to limit by date.</li>
        <li><strong>Export CSV</strong> downloads exactly what the list shows.</li>
    </ol>
    
</details>
<details>
    <summary>Notes and your attendance QR</summary>
    <p class="dash-guide-where">Where: Dashboard</p>
    <ol>
        <li>Add private reminders in <strong>My notes</strong> on your dashboard; tick them when done.</li>
        <li>Students and staff see their <strong>attendance QR</strong> on the dashboard. Tap it to make it big and show it at the gate kiosk.</li>
        <li>Your printable ID card is under <strong>My ID Card</strong>.</li>
    </ol>
    
</details>
