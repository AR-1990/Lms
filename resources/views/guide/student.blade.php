{{-- User guide: student. --}}
<p>Your day, tests and results in one place.</p>
<details>
    <summary>Take an online test</summary>
    <p class="dash-guide-where">Where: Menu → Online Tests</p>
    <ol>
        <li>Open tests show a <strong>Start</strong> button. The timer starts when you press it.</li>
        <li>Choose one answer per question. Every answer is saved as you go, so a lost connection or refresh loses nothing.</li>
        <li>Press <strong>Submit test</strong>. When the time ends the test is submitted for you.</li>
        <li>Your score shows at once; the teacher may also let you see the right answers.</li>
    </ol>
    <p class="dash-guide-tip">Each test can be taken only once.</p>
</details>
<details>
    <summary>See your results</summary>
    <p class="dash-guide-where">Where: Menu → Results</p>
    <ol>
        <li>Published exam results with subject marks, grades and position.</li>
        <li>Download the result card from My School Day → Exams &amp; Results.</li>
    </ol>
    
</details>
<details>
    <summary>Attendance at the gate</summary>
    <p class="dash-guide-where">Where: Dashboard</p>
    <ol>
        <li>Show the QR on your dashboard or your ID card to the gate kiosk camera.</li>
        <li>Your attendance is marked and your parents are told you arrived.</li>
    </ol>
    
</details>
