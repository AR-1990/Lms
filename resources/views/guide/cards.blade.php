{{-- User guide: cards. --}}
<p>ID cards, admit cards and passes are printed from the system.</p>
<details>
    <summary>Issue and print ID cards</summary>
    <p class="dash-guide-where">Where: ID Cards</p>
    <ol>
        <li>Issue cards for a class, department or chosen people.</li>
        <li>Print them on A4 sheets; the QR on each card is used for gate attendance.</li>
        <li>Mark a card lost to issue a replacement.</li>
    </ol>
    
</details>
<details>
    <summary>Design a card</summary>
    <p class="dash-guide-where">Where: ID Cards → Templates</p>
    <ol>
        <li>Pick a design (classic, wave, elegant or modern) and drag items such as photo, name, logo and QR.</li>
    </ol>
    
</details>
