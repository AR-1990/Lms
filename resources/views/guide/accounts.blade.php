{{-- User guide: accounts. --}}
<p>Every fee, salary and expense posts to the ledger by itself.</p>
<details>
    <summary>Ledger and vouchers</summary>
    <p class="dash-guide-where">Where: Accounts</p>
    <ol>
        <li>Chart of accounts, journal / payment / receipt vouchers, fiscal years.</li>
        <li>Posted vouchers are corrected by reversal, never edited.</li>
    </ol>
    
</details>
<details>
    <summary>Expenses and vendors</summary>
    <p class="dash-guide-where">Where: Accounts → Expenses · Vendors</p>
    <ol>
        <li>Record an expense with its bill; it is paid after approval.</li>
        <li>Pay vendor bills; see vendor balances.</li>
    </ol>
    
</details>
<details>
    <summary>Bank reconciliation and reports</summary>
    <p class="dash-guide-where">Where: Accounts → Bank Reconciliation · Reports</p>
    <ol>
        <li>Tick bank statement lines against the ledger each month.</li>
        <li>Trial balance, balance sheet, income and fee reports, with CSV and PDF.</li>
    </ol>
    
</details>
